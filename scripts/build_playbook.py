"""Build mcp/lib/auto/playbook-docs.ts from the repo's rules and docs, so the `playbook` MCP tool can hand any model the
part it needs (CLAUDE.md, docs/FEEDBACK.md, docs/DESIGN.md, docs/AUTOMATION.md and the rest), by section.

  python3 scripts/build_playbook.py

Run by the deploy workflow before every deploy (so the served copy is never stale); run it locally after editing docs.
"""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = [("claude", "CLAUDE.md", "How to work in this repo: shipping, design, security, checks")]
for name in sorted(os.listdir(os.path.join(ROOT, "docs"))):
    if name.endswith(".md"):
        DOCS.append((name[:-3].lower(), f"docs/{name}", ""))


def sections(text):
    """Split on ## headings; the part before the first one is the intro. Each keeps its own ### subsections."""
    out, title, buf = [], "Intro", []
    for line in text.splitlines():
        m = re.match(r"^##\s+(.*)", line)
        if m:
            if "".join(buf).strip():
                out.append({"title": title, "text": "\n".join(buf).strip()})
            title, buf = m.group(1).strip(), []
        else:
            buf.append(line)
    if "".join(buf).strip():
        out.append({"title": title, "text": "\n".join(buf).strip()})
    return out


docs = []
for key, rel, about in DOCS:
    text = open(os.path.join(ROOT, rel), encoding="utf-8").read()
    first = next((ln.lstrip("# ").strip() for ln in text.splitlines() if ln.startswith("# ")), rel)
    docs.append({"id": key, "path": rel, "title": first, "about": about, "sections": sections(text)})

out = os.path.join(ROOT, "mcp", "lib", "auto", "playbook-docs.ts")
with open(out, "w", encoding="utf-8") as f:
    f.write("// Generated by scripts/build_playbook.py from CLAUDE.md and docs/. Do not edit.\n")
    f.write("export type Doc = { id: string; path: string; title: string; about: string; sections: { title: string; text: string }[] };\n")
    f.write(f"export const DOCS: Doc[] = {json.dumps(docs, ensure_ascii=False, indent=0)};\n")
print(f"{out}: {len(docs)} docs, {sum(len(d['sections']) for d in docs)} sections")
